export function getLocaleDir(locale: Locale): "ltr" | "rtl" {
  return locale === "ur" || locale === "ar" ? "rtl" : "ltr";
}

export function isLocale(value: string | undefined): value is Locale {
  return !!value && LOCALES.some((l) => l.code === value);
}

